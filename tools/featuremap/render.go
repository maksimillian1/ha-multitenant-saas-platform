package main

import (
	"fmt"
	"strings"
)

// renderMap builds docs/features/map.md from the feature files alone. It does
// not look at git, so the map changes only when a feature file changes.
func renderMap(features []*Feature) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by tools/featuremap from docs/features/*.yaml. Do not edit: run `go -C tools/featuremap run .` -->\n\n")
	b.WriteString("# Feature map\n\n")
	b.WriteString("Each feature's stage and the gates behind it ([Feature stages](../process/feature-stages.md), \"Gates per stage\"). How to read it: [Features](README.md).\n\n")
	b.WriteString("✓ pass · ✗ fail · n/a not applicable · ? not checked · blank: not recorded · (owner): marked by the owner\n\n")

	b.WriteString("| Feature | Stage |")
	for _, id := range gateIDs {
		b.WriteString(" " + id + " |")
	}
	b.WriteString(" Last verify | Issues |\n|---|---|")
	for range gateIDs {
		b.WriteString("---|")
	}
	b.WriteString("---|---|\n")

	for _, f := range features {
		name := fmt.Sprintf("[`%s`](%s.yaml)", f.Feature, f.Feature)
		if f.Critical {
			name += " **critical**"
		}
		fmt.Fprintf(&b, "| %s | %s |", name, orDash(f.Stage))
		for _, id := range gateIDs {
			b.WriteString(" " + gateCell(f, id) + " |")
		}
		fmt.Fprintf(&b, " %s | %s |\n", lastVerify(f), strings.Join(f.Links.Issues, ", "))
	}
	return b.String()
}

func lastVerify(f *Feature) string {
	if len(f.Runs) == 0 {
		return "—"
	}
	r := f.Runs[len(f.Runs)-1]
	return fmt.Sprintf("%s %s for %s", r.Date, r.Verdict, r.StageChecked)
}

// lastReview is the owner's code review, gate G-06.
func lastReview(f *Feature) (string, string) {
	g, ok := f.Gates["G-06"]
	if !ok || g.Status != "pass" {
		return "—", ""
	}
	return fmt.Sprintf("%s at %s", g.Date, short(g.Commit)), g.Commit
}

func short(commit string) string {
	if len(commit) > 7 {
		return commit[:7]
	}
	return commit
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}
