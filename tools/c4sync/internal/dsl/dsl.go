// Package dsl writes the model as Structurizr DSL, the only output format of
// c4sync. Structurizr CLI renders it to Mermaid, PlantUML or images.
//
// Nothing here depends on line numbers, so moving code does not make the
// output stale; only structural changes do.
package dsl

import (
	"fmt"
	"sort"
	"strings"

	"github.com/maksimillian1/ha-multitenant-saas-platform/tools/c4sync/internal/model"
)

// Tag on every generated element and relation.
const Tag = "c4sync"

// Options control the writers.
type Options struct {
	Prefix      string // identifier prefix of components
	MaxElements int    // per code view
	MaxMethods  int    // per code element
}

// Components writes the C3 fragment to !include inside a container block.
// Relations to external elements use the workspace identifiers from the config.
func Components(m *model.Model, o Options) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by c4sync from %s. Do not edit.\n", m.Container)
	writeComponents(&b, m, o.Prefix, "", func(id string) string { return id })
	return b.String()
}

// Code writes a standalone workspace with the code level of every component:
// one container for the code, a group per component, Go types as components,
// and one view per component.
func Code(m *model.Model, o Options) string {
	var b strings.Builder
	fmt.Fprintf(&b, "workspace %s %s {\n", q(m.Container+": code"), q("Generated by c4sync. Do not edit."))
	b.WriteString("    !identifiers hierarchical\n\n    model {\n")
	fmt.Fprintf(&b, "        code = softwareSystem %s {\n", q(m.Container))
	fmt.Fprintf(&b, "            src = container %s %s %s %s {\n", q(m.Container+" code"), q(""), q("Go"), q(Tag))
	writeCode(&b, m, "                ", nil, o.MaxMethods)
	b.WriteString("            }\n        }\n    }\n\n    views {\n")
	for _, c := range m.Components {
		writeCodeView(&b, m, c.ID, "code.src", o, "        ")
	}
	writeStyles(&b, "        ")
	b.WriteString("    }\n}\n")
	return b.String()
}

// Changes writes a standalone workspace with views of the given components
// only: their C3 neighbourhood and their code level. diff uses it so that a
// report can show just what changed.
func Changes(m *model.Model, comps []string, o Options) string {
	keep := map[string]bool{}
	for _, c := range comps {
		keep[c] = true
	}
	ext := map[string]string{}
	for _, r := range m.ExternalRelations {
		ext[r.To] = "x_" + sanitize(r.To)
	}
	for _, i := range m.Interfaces {
		if i.Element != "" {
			ext[i.Element] = "x_" + sanitize(i.Element)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "workspace %s %s {\n", q(m.Container+": changes"), q("Generated by c4sync diff. Do not edit."))
	b.WriteString("    !identifiers hierarchical\n\n    model {\n")
	for _, id := range sortedKeys(ext) {
		fmt.Fprintf(&b, "        %s = softwareSystem %s %s %s\n", ext[id], q(id), q("External element"), q(Tag))
	}
	fmt.Fprintf(&b, "        sys = softwareSystem %s {\n", q(m.Container))
	fmt.Fprintf(&b, "            svc = container %s %s %s %s {\n", q(m.Container), q(""), q("Go"), q(Tag))
	writeComponents(&b, m, o.Prefix, "                ", func(id string) string {
		if v, ok := ext[id]; ok {
			return v
		}
		return id
	})
	b.WriteString("            }\n")
	fmt.Fprintf(&b, "            src = container %s %s %s %s {\n", q(m.Container+" code"), q(""), q("Go"), q(Tag))
	writeCode(&b, m, "                ", keep, o.MaxMethods)
	b.WriteString("            }\n        }\n    }\n\n    views {\n")

	var c3 []string
	for _, c := range m.Components {
		if keep[c.ID] {
			c3 = append(c3, "sys.svc."+compIdent(o.Prefix, c.ID))
		}
	}
	if len(c3) > 0 {
		fmt.Fprintf(&b, "        component sys.svc %s %s {\n", q("changes"), q("Changed components"))
		for _, id := range c3 {
			fmt.Fprintf(&b, "            include \"->%s->\"\n", id)
		}
		b.WriteString("            autoLayout lr\n        }\n")
	}
	for _, c := range comps {
		writeCodeView(&b, m, c, "sys.src", o, "        ")
	}
	writeStyles(&b, "        ")
	b.WriteString("    }\n}\n")
	return b.String()
}

func writeComponents(b *strings.Builder, m *model.Model, prefix, indent string, ext func(string) string) {
	props := interfaceProperties(m)
	for _, c := range m.Components {
		tags := append([]string{Tag}, c.Tags...)
		fmt.Fprintf(b, "%s%s = component %s %s %s %s {\n", indent, compIdent(prefix, c.ID),
			q(c.Name), q(c.Description), q(c.Technology), q(strings.Join(tags, ",")))
		fmt.Fprintf(b, "%s    properties {\n", indent)
		fmt.Fprintf(b, "%s        %s %s\n", indent, q("go.packages"), q(strings.Join(relPackages(m.Module, c.Packages), " ")))
		for _, p := range props[c.ID] {
			fmt.Fprintf(b, "%s        %s %s\n", indent, q(p[0]), q(p[1]))
		}
		fmt.Fprintf(b, "%s    }\n%s}\n", indent, indent)
	}
	for _, r := range m.Relations {
		fmt.Fprintf(b, "%s%s -> %s %s %s %s\n", indent, compIdent(prefix, r.From), compIdent(prefix, r.To),
			q("Uses"), q("Go import"), q(Tag))
	}
	for _, r := range m.ExternalRelations {
		fmt.Fprintf(b, "%s%s -> %s %s %s %s\n", indent, compIdent(prefix, r.From), ext(r.To),
			q(r.Description), q(r.Technology), q(Tag))
	}
	for _, r := range interfaceRelations(m) {
		fmt.Fprintf(b, "%s%s -> %s %s %s %s\n", indent, compIdent(prefix, r.from), ext(r.to),
			q(r.desc), q(""), q(Tag))
	}
}

// interfaceProperties lists, per component, "kind.direction" -> names.
func interfaceProperties(m *model.Model) map[string][][2]string {
	group := map[string]map[string][]string{}
	for _, i := range m.Interfaces {
		if group[i.Component] == nil {
			group[i.Component] = map[string][]string{}
		}
		k := i.Kind + "." + i.Direction
		group[i.Component][k] = append(group[i.Component][k], label(i))
	}
	out := map[string][][2]string{}
	for c, g := range group {
		for _, k := range sortedKeys(g) {
			out[c] = append(out[c], [2]string{k, strings.Join(uniq(g[k]), ", ")})
		}
	}
	return out
}

func label(i model.ExternalInterface) string {
	if i.Unresolved {
		return "? (in " + i.Where + ")"
	}
	return i.Name
}

type ifaceRel struct{ from, to, desc string }

// interfaceRelations draws one relation per component, element and direction,
// for example "Produces topics: a, b".
func interfaceRelations(m *model.Model) []ifaceRel {
	type key struct{ from, to, kind, dir string }
	names := map[key][]string{}
	var keys []key
	for _, i := range m.Interfaces {
		if i.Element == "" {
			continue
		}
		k := key{i.Component, i.Element, i.Kind, i.Direction}
		if _, ok := names[k]; !ok {
			keys = append(keys, k)
		}
		names[k] = append(names[k], label(i))
	}
	sort.Slice(keys, func(a, b int) bool {
		x, y := keys[a], keys[b]
		return strings.Join([]string{x.from, x.to, x.kind, x.dir}, "\x00") < strings.Join([]string{y.from, y.to, y.kind, y.dir}, "\x00")
	})
	var out []ifaceRel
	for _, k := range keys {
		noun := map[string]string{model.Topic: "topics", model.Table: "tables", model.HTTP: "routes"}[k.kind]
		if k.dir == model.Calls {
			noun = "functions"
		}
		verb := strings.ToUpper(k.dir[:1]) + k.dir[1:]
		out = append(out, ifaceRel{k.from, k.to, fmt.Sprintf("%s %s: %s", verb, noun, strings.Join(uniq(names[k]), ", "))})
	}
	return out
}

// writeCode writes groups of code elements and their relations. When keep is
// not nil, only elements of those components and their direct neighbours are written.
func writeCode(b *strings.Builder, m *model.Model, indent string, keep map[string]bool, maxMethods int) {
	include := map[string]bool{}
	for _, e := range m.CodeElements {
		if keep == nil || keep[e.Component] {
			include[e.ID] = true
		}
	}
	if keep != nil {
		byID := elementsByID(m)
		for _, r := range m.CodeRelations {
			if keep[byID[r.From].Component] || keep[byID[r.To].Component] {
				include[r.From], include[r.To] = true, true
			}
		}
	}
	names := map[string]string{}
	for _, c := range m.Components {
		names[c.ID] = c.Name
	}
	byComp := map[string][]model.CodeElement{}
	for _, e := range m.CodeElements {
		if include[e.ID] {
			byComp[e.Component] = append(byComp[e.Component], e)
		}
	}
	display := elementNames(m)
	for _, c := range sortedKeys(byComp) {
		fmt.Fprintf(b, "%sgroup %s {\n", indent, q(names[c]))
		for _, e := range byComp[c] {
			fmt.Fprintf(b, "%s    %s = component %s %s %s %s\n", indent, elemIdent(e.ID), q(display[e.ID]),
				q(elementDescription(e, maxMethods)), q(""), q(Tag+","+kindTag(e.Kind)))
		}
		fmt.Fprintf(b, "%s}\n", indent)
	}
	for _, r := range m.CodeRelations {
		if include[r.From] && include[r.To] {
			fmt.Fprintf(b, "%s%s -> %s %s %s %s\n", indent, elemIdent(r.From), elemIdent(r.To), q(r.Kind), q(""), q(Tag+","+r.Kind))
		}
	}
}

// writeCodeView writes the view of one component: its own elements (exported
// first) and then the elements they are related to, up to MaxElements.
func writeCodeView(b *strings.Builder, m *model.Model, comp, container string, o Options, indent string) {
	var own []model.CodeElement
	for _, e := range m.CodeElements {
		if e.Component == comp {
			own = append(own, e)
		}
	}
	if len(own) == 0 {
		return
	}
	sort.SliceStable(own, func(i, j int) bool { return own[i].Exported && !own[j].Exported })
	var ids []string
	in := map[string]bool{}
	dropped := 0
	for _, e := range own {
		if len(ids) >= o.MaxElements {
			dropped++
			continue
		}
		ids = append(ids, e.ID)
		in[e.ID] = true
	}
	var neighbours []string
	for _, r := range m.CodeRelations {
		if in[r.From] && !in[r.To] {
			neighbours = append(neighbours, r.To)
		}
		if in[r.To] && !in[r.From] {
			neighbours = append(neighbours, r.From)
		}
	}
	for _, n := range uniq(neighbours) {
		if len(ids) >= o.MaxElements {
			break
		}
		if !in[n] {
			ids = append(ids, n)
			in[n] = true
		}
	}
	name := comp
	if c := m.Component(comp); c != nil {
		name = c.Name
	}
	title := name + ": code"
	if dropped > 0 {
		title += fmt.Sprintf(" (%d unexported types not shown)", dropped)
	}
	fmt.Fprintf(b, "%scomponent %s %s %s {\n", indent, container, q("code_"+sanitize(comp)), q(title))
	for _, id := range ids {
		fmt.Fprintf(b, "%s    include %s.%s\n", indent, container, elemIdent(id))
	}
	fmt.Fprintf(b, "%s    autoLayout lr\n%s}\n", indent, indent)
}

func writeStyles(b *strings.Builder, indent string) {
	fmt.Fprintf(b, "%sstyles {\n", indent)
	fmt.Fprintf(b, "%s    element \"Interface\" {\n%s        border dashed\n%s        metadata false\n%s    }\n", indent, indent, indent, indent)
	fmt.Fprintf(b, "%s    element \"Struct\" {\n%s        metadata false\n%s    }\n", indent, indent, indent)
	fmt.Fprintf(b, "%s    element \"Type\" {\n%s        metadata false\n%s    }\n", indent, indent, indent)
	fmt.Fprintf(b, "%s}\n", indent)
}

func kindTag(kind string) string {
	switch kind {
	case model.Struct:
		return "Struct"
	case model.Interface:
		return "Interface"
	}
	return "Type"
}

// elementNames gives every code element a name that is unique in the
// container, as Structurizr requires: "pkg.Type", or "rel/path.Type" when two
// packages share the last path element.
func elementNames(m *model.Model) map[string]string {
	short := func(p string) string { return p[strings.LastIndex(p, "/")+1:] }
	owners := map[string]map[string]bool{}
	for _, e := range m.CodeElements {
		s := short(e.Package)
		if owners[s] == nil {
			owners[s] = map[string]bool{}
		}
		owners[s][e.Package] = true
	}
	out := map[string]string{}
	for _, e := range m.CodeElements {
		pkg := short(e.Package)
		if len(owners[pkg]) > 1 {
			pkg = strings.TrimPrefix(strings.TrimPrefix(e.Package, m.Module), "/")
		}
		out[e.ID] = pkg + "." + e.Name
	}
	return out
}

func elementDescription(e model.CodeElement, max int) string {
	desc := e.Kind
	if len(e.Methods) == 0 {
		return desc
	}
	ms := e.Methods
	more := ""
	if max > 0 && len(ms) > max {
		more = fmt.Sprintf("; +%d more", len(ms)-max)
		ms = ms[:max]
	}
	return desc + ": " + strings.Join(ms, "; ") + more
}

func elementsByID(m *model.Model) map[string]model.CodeElement {
	out := map[string]model.CodeElement{}
	for _, e := range m.CodeElements {
		out[e.ID] = e
	}
	return out
}

func relPackages(module string, pkgs []string) []string {
	out := make([]string, len(pkgs))
	for i, p := range pkgs {
		r := strings.TrimPrefix(strings.TrimPrefix(p, module), "/")
		if r == "" {
			r = "."
		}
		out[i] = r
	}
	return out
}

func compIdent(prefix, id string) string { return prefix + "_" + caseSafe(sanitize(id)) }

func elemIdent(id string) string { return "t_" + caseSafe(sanitize(id)) }

// caseSafe writes an upper-case letter as "-" and the lower-case letter.
// Structurizr compares identifiers without regard to case, so Go names that
// differ only in case (humanUpdate, HumanUpdate) would otherwise clash.
func caseSafe(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= 'A' && r <= 'Z' {
			b.WriteByte('-')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func sanitize(s string) string {
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' {
			return r
		}
		return '_'
	}, s)
}

func q(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}

func uniq(s []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range s {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
